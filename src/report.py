"""Run every experiment and write ONE results document: docs/results.md

This is the evidence for the project: baselines vs gradient boosting, the ablation,
interval honesty (coverage, WIS), and equity breakdowns by urban/rural and district size.

Run:  python src/report.py        (about 1 minute)
"""
from datetime import date
from pathlib import Path

import pandas as pd

from evaluate import FIRST_ORIGIN, HORIZON, STEP, rolling_origin
from gbm import TESTING_FEATURES, gbm_rolling_origin
from intervals import interval_rolling_origin


def md_table(df, index_name="", digits=2):
    """Small markdown table writer (no extra libraries needed)."""
    cols = list(df.columns)
    head = "| " + " | ".join([index_name] + [str(c) for c in cols]) + " |"
    rule = "|" + "---|" * (len(cols) + 1)
    rows = []
    for idx, row in df.iterrows():
        cells = [f"{v:.{digits}f}" if isinstance(v, float) else str(v) for v in row]
        rows.append("| " + " | ".join([str(idx)] + cells) + " |")
    return "\n".join([head, rule] + rows)


def mase_table(res, by):
    return res.pivot_table(index="model", columns=by, values="scaled_error").round(2)


def main():
    df = pd.read_csv("data/synthetic/district_months.csv")
    print("Running baselines ...")
    acc = pd.concat([
        rolling_origin(df),
        gbm_rolling_origin(df),
        gbm_rolling_origin(df, exclude=TESTING_FEATURES, name="gbm_no_testing"),
    ], ignore_index=True)
    print("Running intervals ...")
    iv = interval_rolling_origin(df)

    overall = acc.groupby("model")["scaled_error"].mean().round(3).to_frame("MASE")
    best_base = overall.loc[["naive", "seasonal_naive", "exp_smoothing"], "MASE"].min()
    gain = (1 - overall.loc["gbm", "MASE"] / best_base) * 100

    parts = []
    for col in ["horizon", "urban_rural", "size_class", "campaign"]:
        t = iv.groupby(col).agg(coverage_80=("in80", "mean"), coverage_95=("in95", "mean"),
                                WIS=("wis_scaled", "mean"), n=("in80", "size")).round(3)
        t["n"] = t["n"].astype(int)
        parts.append(f"**By {col}**\n\n" + md_table(t, col, 3))

    g = mase_table(acc, "urban_rural")
    gs = mase_table(acc, "size_class")
    gap_rows = pd.DataFrame({
        "gbm MASE": [g.loc["gbm", "rural"], g.loc["gbm", "urban"], gs.loc["gbm", "small"], gs.loc["gbm", "large"]],
    }, index=["rural", "urban", "small districts", "large districts"])

    text = f"""# Results (SYNTHETIC DATA ONLY)

Generated {date.today().isoformat()} by `src/report.py`. These results show that the workflow
works. They say NOTHING about Malawi, because the data were generated by `src/generate_data.py`.

## Setup
- Target: monthly new HIV diagnoses per district (a proxy for infections; depends on testing)
- {df['district'].nunique()} districts x {df['month_index'].nunique()} months; {int(df['new_diagnoses'].isna().sum())} blank months ({df['new_diagnoses'].isna().mean():.1%})
- Evaluation: rolling origin, first cut-off month {FIRST_ORIGIN}, every {STEP} months, horizons 1 to {HORIZON}
- Metric: MASE (1.0 = about as good as repeating last month; lower is better)

## 1. Accuracy
Overall MASE by model:

{md_table(overall, "model", 3)}

Gradient boosting is {gain:.0f}% better than the best baseline overall.

**By horizon (months ahead)**

{md_table(mase_table(acc, "horizon"), "model")}

**By urban/rural**

{md_table(g, "model")}

**By district size**

{md_table(gs, "model")}

**Campaign months (1) vs normal months (0)**

{md_table(mase_table(acc, "campaign"), "model")}

## 2. Ablation: does knowing about testing help?
`gbm_no_testing` hides the four testing inputs. If its score is close to `gbm`, the gain over
the baselines does not come from testing information.

## 3. Interval honesty
80% and 95% prediction intervals from quantile gradient boosting. Coverage is the share of
real outcomes inside the interval (targets: 0.80 and 0.95). WIS is the scaled weighted interval score.

Overall: coverage 80% = {iv.in80.mean():.3f}, coverage 95% = {iv.in95.mean():.3f}, WIS = {iv.wis_scaled.mean():.3f}

""" + "\n\n".join(parts) + f"""

## 4. Equity summary (gradient boosting)

{md_table(gap_rows, "group", 2)}

Rural districts and small districts are harder to forecast. Campaign months break every method.
Group sizes differ greatly (see n above), so small differences should not be over-interpreted.

## 5. Limitations
- Synthetic data: patterns were built in by us, so results are optimistic and not about Malawi
- Diagnoses are a proxy for infections and depend on testing; campaign timing is unknown to the models
- No tuning: gradient boosting settings were chosen once, not optimised
- Forecasts from the same district are correlated, so effective sample sizes are smaller than n
- Intervals are mildly overconfident and fail in campaign months
"""
    Path("docs").mkdir(exist_ok=True)
    Path("docs/results.md").write_text(text)
    print("Wrote docs/results.md")


if __name__ == "__main__":
    main()
